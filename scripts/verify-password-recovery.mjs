import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (p) => readFileSync(p, 'utf8');
const index = read('index.html');
const app = read('js/core/app.js');
const profiles = read('js/data/profiles.js');
const session = read('js/finance/orchestration/procesar-sesion.js');
const recoveryUi = read('js/auth/password-recovery.js');
const recoveryEdge = read('supabase/functions/recuperar-contrasena/index.ts');
const frontendWorkflow = read('.github/workflows/step10-frontend.yml');

assert.match(index, /id="btn-olvido-contrasena"/, 'Login must expose a forgotten-password action');
assert.match(index, /id="form-solicitar-recuperacion"/, 'Recovery must have a request form');
assert.match(index, /id="form-confirmar-recuperacion"/, 'Recovery must have a code + new-password form');
assert.match(index, /password-recovery\.js\?v=142/, 'Recovery UI must use a cache-busted release URL');
assert.match(recoveryUi, /mode: "request"/, 'UI must request a code');
assert.match(recoveryUi, /mode: "complete"/, 'UI must submit the code and new password');
assert.match(recoveryEdge, /origin !== APP_ORIGIN/, 'Recovery Edge Function must enforce the exact production origin');
assert.match(recoveryEdge, /MAX_ATTEMPTS_PER_IP/, 'Recovery must rate-limit requests');
assert.match(recoveryEdge, /data\.estado !== "activo"/, 'Inactive and archived profiles must not be recoverable');
assert.match(recoveryEdge, /shouldCreateUser: true/, 'Recovery must send OTP to the profile contact email even for internal @cuevacoin.local Auth IDs');
assert.match(recoveryEdge, /auth\.verifyOtp/, 'Email ownership must be verified before changing a password');
assert.match(recoveryEdge, /auth\.admin\.updateUserById/, 'Password update must target the original profile/Auth UUID');
assert.match(recoveryEdge, /verified\.user\.email\?\.trim\(\)\.toLowerCase\(\) !== profile\.correo\.toLowerCase\(\)/, 'Verified email must match the target profile contact email');
assert.doesNotMatch(recoveryEdge, /return reply\(\{\s*(?:email|correo|userEmail)\s*:/i, 'Recovery must never return account email information');
assert.match(profiles, /obtenerMiPerfilApp\(usuarioAuth = null\)/, 'Profile lookup should accept a previously loaded session user');
assert.match(session, /obtenerMiPerfilApp\(session\.user\)/, 'Boot must reuse the session user instead of another Auth network round trip');
assert.match(app, /esFalloDeConexionConfirmado/, 'Offline fallback must require a confirmed connectivity failure');
assert.ok(app.includes('/timeout|abort|timed out/i'), 'A timeout alone must not be treated as true offline state');
assert.match(session, /await window\.esFalloDeConexionConfirmado\(err\)/, 'Session boot catches must verify offline state before showing cached data');
assert.match(recoveryEdge, /accepted: true/, 'Recovery initiation must use a generic anti-enumeration response');
assert.ok(frontendWorkflow.includes('node scripts/verify-password-recovery.mjs'), 'CI must run recovery and startup regression tests');
console.log('PASS — password recovery UI and server-side OTP flow are wired');
console.log('PASS — inactive/archived profiles and account-enumeration protections are enforced');
console.log('PASS — boot avoids redundant Auth round trip and only enables cached/offline mode on confirmed connectivity failure');